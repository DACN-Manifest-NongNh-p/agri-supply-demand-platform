import { useEffect, useRef, useState } from "react";
import { Sparkles, X } from "lucide-react";
import type { Insight } from "../data/mockProducer";
import { formatDay } from "../data/format";

/**
 * "From the market": a clean, text-only headline list. Images, analysis, evidence and sources
 * appear only in the detail dialog.
 */
export function MarketInsights({ insights }: { insights: Insight[] }) {
  const [openId, setOpenId] = useState<string | null>(null);
  const open = insights.find((insight) => insight.id === openId);

  return (
    <section className="ph-news" aria-labelledby="signals-title">
      <div className="ph-news-head">
        <h2 id="signals-title">From the market</h2>
        <span className="ph-ai-badge"><Sparkles size={12} /> AI insights</span>
      </div>

      <ul className="ph-news-list">
        {insights.map((insight) => (
          <li key={insight.id}>
            <button type="button" className="ph-news-item" onClick={() => setOpenId(insight.id)}>
              <span className="ph-news-item-top">
                <span className={`ph-news-kicker ph-news-kicker--${insight.category.toLowerCase()}`}>{insight.category}</span>
                <span className="ph-news-item-time">{formatDay(insight.generatedDay)}</span>
              </span>
              <span className="ph-news-item-title">{insight.title}</span>
              <span className="ph-news-summary">{insight.summary}</span>
            </button>
          </li>
        ))}
      </ul>

      {open && <InsightDialog insight={open} onClose={() => setOpenId(null)} />}
    </section>
  );
}

function InsightDialog({ insight, onClose }: { insight: Insight; onClose: () => void }) {
  const dialogRef = useRef<HTMLDialogElement>(null);

  // showModal() gives focus trapping, Esc to close and an inert background for free.
  // No close() in cleanup: StrictMode re-runs effects, and close() would fire onClose and unmount us.
  // Removing the element on unmount ends the modal state anyway.
  useEffect(() => {
    const dialog = dialogRef.current;
    if (dialog && !dialog.open) dialog.showModal();
  }, []);

  return (
    <dialog
      ref={dialogRef}
      className="ph-insight-dialog"
      aria-labelledby="insight-title"
      onClose={onClose}
      onClick={(event) => {
        // A click on the backdrop lands on the <dialog> element itself.
        if (event.target === event.currentTarget) onClose();
      }}
    >
      <header className="ph-insight-hero">
        <img src={insight.image} alt="" />
        <button type="button" className="ph-insight-close" onClick={onClose} aria-label="Close">
          <X size={18} />
        </button>
        <div className="ph-insight-hero-text">
          <span className={`ph-news-tag ph-news-tag--${insight.category.toLowerCase()}`}>{insight.category}</span>
          <h2 id="insight-title">{insight.title}</h2>
          <p>
            <Sparkles size={12} /> AI market insight · generated {formatDay(insight.generatedDay).toLowerCase()} · {insight.confidence} confidence
          </p>
        </div>
      </header>

      <div className="ph-insight-dialog-body">
        <p className="ph-insight-dialog-summary">{insight.summary}</p>

        <section aria-labelledby="insight-analysis">
          <h3 id="insight-analysis" className="ph-insight-h3">AI analysis</h3>
          {insight.analysis.map((paragraph) => (
            <p key={paragraph} className="ph-insight-paragraph">{paragraph}</p>
          ))}
        </section>

        <section aria-labelledby="insight-evidence">
          <h3 id="insight-evidence" className="ph-insight-h3">Evidence</h3>
          <dl className="ph-evidence">
            {insight.evidence.map((item) => (
              <div key={item.label} className="ph-evidence-item">
                <dt>{item.label}</dt>
                <dd>
                  <strong>{item.value}</strong>
                  <span>{item.note}</span>
                </dd>
              </div>
            ))}
          </dl>
        </section>

        <section aria-labelledby="insight-sources">
          <h3 id="insight-sources" className="ph-insight-h3">Market sources</h3>
          <ol className="ph-sources">
            {insight.sources.map((source) => (
              <li key={source.name}>
                <p className="ph-source-name">
                  {source.name}
                  <span>{source.kind} · {formatDay(source.day)}</span>
                </p>
                <blockquote>{source.excerpt}</blockquote>
              </li>
            ))}
          </ol>
        </section>

        <p className="ph-insight-disclaimer">
          This insight is generated by AI from the sources above. Use it as guidance alongside your own judgement.
        </p>
      </div>
    </dialog>
  );
}
